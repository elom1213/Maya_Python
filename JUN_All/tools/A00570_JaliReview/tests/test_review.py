# A00570_JaliReview - 코어 시험 (T7, mayapy 2024): 클립 2개를 A00560 워커로 만들고 검수 씬 왕복
#   "C:\Program Files\Autodesk\Maya2024\bin\mayapy.exe" test_review.py
# build -> connect(51/52 보고) -> 키 편집 -> Swap 차단 -> Save -> 클립 재열기 값 변경 -> Swap 성공 -> 연결 유지 -> Discard -> Open Clip
import json
import os
import shutil
import subprocess
import sys
import tempfile

import maya.standalone
maya.standalone.initialize(name="python")
import maya.cmds as cmds

JUN_ALL = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
sys.path.insert(0, JUN_ALL)
from Framework.core import mayapy_runner   # noqa: E402
from Framework.jali import clip_manifest   # noqa: E402
from tools.A00570_JaliReview.app.core import review_scene as rs, arkit_connect   # noqa: E402

SRC = r"C:\Users\USER\Desktop\JP\0030_maya_python_JUN\JUN_JALI_Voice\0060_Vivian_voice\out_en_002"
CTL_SRC = r"C:\Users\USER\Desktop\JP\0035_maya_src_rig\02_Cage_JALI\A0030_jali_slider_ctl_direct_arkit.ma"
WORKER = os.path.join(JUN_ALL, "tools", "A00560_JaliBatch", "app", "maya", "worker.py")
R = []


def check(name, cond, extra=""):
    R.append(bool(cond))
    print(("PASS " if cond else "FAIL ") + name + ("  | " + str(extra) if extra else ""))


def finish():
    print("RESULT", "OK" if all(R) else "FAIL", "{0}/{1}".format(sum(R), len(R)))
    maya.standalone.uninitialize()
    os._exit(0 if all(R) else 1)


if not os.path.isdir(SRC) or not os.path.isfile(CTL_SRC):
    print("SKIP no example data / controller")
    print("RESULT OK (skipped)")
    maya.standalone.uninitialize()
    os._exit(0)

work = tempfile.mkdtemp(prefix="a00570_")
CTL = os.path.join(work, "A0030_ctl.ma")
shutil.copy2(CTL_SRC, CTL)
OUT = os.path.join(work, "maya")

# ---- 클립 2개 (A00560 워커, 실제 하위 프로세스)
names = ["0030_vivian_en_02_f0445_0490", "0030_vivian_en_03_f0490_0600"]
clips = [{"name": n, "txt": os.path.join(SRC, n + ".txt"), "json": os.path.join(SRC, n + ".visemenet.json"),
          "wav": os.path.join(SRC, n + ".wav"), "out_mb": os.path.join(OUT, n + ".mb"), "start": 1} for n in names]
job = {"job": "generate", "controller": CTL, "mapping": "jali_slider_dummy_in", "fps": 30.0, "default_start": 1,
       "jali": {"mode": "data", "fixed": [0.6, 0.6], "scale": None}, "viseme_scale": None, "overwrite": "skip", "copy_wav": True,
       "out_dir": OUT, "manifest": clip_manifest.path_for(OUT), "tool": "test", "clips": clips}
job_dir = mayapy_runner.new_job_dir("a00570_test")
job_path, result_path, _ = mayapy_runner.write_job(job_dir, job)
proc = subprocess.run(mayapy_runner.command(sys.executable, job_path, WORKER), stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, errors="replace")
result = mayapy_runner.read_result(result_path) if os.path.isfile(result_path) else None
check("P0 two clips generated by the A00560 worker", result and result["generated"] == 2, (proc.returncode, result and result.get("failed")))
if not result or result["generated"] != 2:
    finish()
mf = clip_manifest.load(OUT)
C1, C2 = clips[0]["out_mb"], clips[1]["out_mb"]

# ---- 가짜 아바타: 평면 + blendShape 51 타겟 (ARKit 52 중 tongueOut 없음)
AVATAR = os.path.join(work, "avatar.mb")
cmds.file(new=True, force=True)
base = cmds.polyPlane(n="face", sx=2, sy=2, ch=False)[0]
arkit = json.load(open(os.path.join(JUN_ALL, "Framework", "jali", "mappings", "jali_slider_dummy_in.json")))  # 이름 확인용 아님
# ARKit 52 이름은 컨트롤러의 ARKIT_OUT 에서 읽는다
cmds.file(CTL, reference=True, namespace="TMP", prompt=False)
arkit52 = [a for a in cmds.listAttr("TMP:ARKIT_OUT", userDefined=True)]
cmds.file(CTL, removeReference=True)
check("P1 controller ARKIT_OUT has 52 attrs", len(arkit52) == 52, len(arkit52))
targets = []
for nm in arkit52:
    if nm == "tongueOut":
        continue
    t = cmds.duplicate(base, n=nm)[0]
    cmds.move(0, 0.1, 0, t + ".vtx[0]", r=True)
    targets.append(t)
bs = cmds.blendShape(targets, base, n="face_bs")[0]
cmds.delete(targets)
cmds.file(rename=AVATAR)
cmds.file(save=True, type="mayaBinary")

# ---- Build review scene
cmds.file(new=True, force=True)
rs.set_scene_fps(30)
check("R1 scene fps ntsc", rs.scene_unit() == "ntsc")
arn = rs.reference_avatar(AVATAR)
rn = rs.reference_clip(C1)
check("R1 clip ref found by namespace", rs.find_clip_ref() == rn and rs.clip_path(rn).lower().replace("/", "\\") == C1.lower())
check("R1 avatar listed as other reference", [n for n, ns, p in rs.other_references()] == [arn])
check("R1 pending edits 0 on a fresh clip (nested clip edits are not counted)", rs.pending_edits(rn) == [])
try:
    rs.reference_clip(C2)
    check("R1 second reference_clip raises", False)
except rs.ReviewError:
    check("R1 second reference_clip raises", True)
check("R1 sound node CLIP:jali_lipsync_audio", rs.clip_sound_node() == "CLIP:jali_lipsync_audio")
e1 = mf["clips"][names[0]]
rs.apply_range(e1["start"], e1["end"])
check("R1 range from manifest", (cmds.playbackOptions(q=True, min=True), cmds.playbackOptions(q=True, max=True)) == (e1["start"], e1["end"]))

# ---- Connect
src = rs.arkit_out_node()
check("R2 ARKIT_OUT found", src == "CLIP:JALI:ARKIT_OUT", src)
res = arkit_connect.connect(src, "{0}:face_bs".format(cmds.referenceQuery(arn, namespace=True, shortName=True)))
bs_full = "{0}:face_bs".format(cmds.referenceQuery(arn, namespace=True, shortName=True))
check("R2 51 connected, tongueOut missing", res["connected"] == 51 and res["missing"] == ["tongueOut"] and not res["failed"], (res["connected"], res["missing"]))
res2 = arkit_connect.connect(src, bs_full)
check("R2 second connect: 51 skipped (already connected)", res2["connected"] == 0 and len(res2["skipped"]) == 51)
check("R2 connected_count", arkit_connect.connected_count(src, bs_full) == 51)
check("R2 connect edits live on the avatar RN, not the clip RN", rs.pending_edits(rn) == [] and
      len(cmds.referenceQuery(arn, editStrings=True, onReferenceNode=arn) or []) >= 51)
rules = {"jawOpen": "mouthClose"}
cmds.undo()
check("R2 undo removes the connections (one chunk)", arkit_connect.connected_count(src, bs_full) == 0)
res3 = arkit_connect.connect(src, bs_full, rules=rules)
# jawOpen 과 mouthClose 둘 다 mouthClose 를 노린다 - 먼저 온 쪽이 붙고 다른 쪽은 "driven by" 로 skip (순서는 ARKIT_OUT 어트리뷰트 순)
first_ok = cmds.isConnected(src + ".jawOpen", bs_full + ".mouthClose") != cmds.isConnected(src + ".mouthClose", bs_full + ".mouthClose")
check("R2 rules remap: jawOpen -> mouthClose (one of the two wins, the other is skipped as driven)", first_ok
      and any(d.endswith(".mouthClose") and ("driven" in why or "planned" in why) for d, why in res3["skipped"]) and not cmds.listConnections(bs_full + ".jawOpen", s=True, d=False))
arkit_connect.disconnect(src, bs_full)
arkit_connect.connect(src, bs_full)

# ---- Edits
curve = "CLIP:JALI_CTL_PH_AAA_ty"
rs.set_anim_curve_edits(False)
v0 = cmds.keyframe(curve, q=True, eval=True, t=(10, 10))[0]
cmds.keyframe(curve, e=True, t=(10, 10), valueChange=0.9)
check("R3 edits OFF: key change ignored", abs(cmds.keyframe(curve, q=True, eval=True, t=(10, 10))[0] - v0) < 1e-9 and not rs.anim_curve_edits_enabled())
rs.set_anim_curve_edits(True)
cmds.keyframe(curve, e=True, t=(10, 10), valueChange=0.9)
cmds.setKeyframe("CLIP:JALI:CTL_PH_AAA.ty", t=400, v=0.5)
pend = rs.pending_edits(rn)
check("R3 edits ON: pending 1 (fcurve relationship)", len(pend) == 1 and rs.classify_edits(pend)["keys"] == pend, pend and pend[0][:80])
check("R3 describe_edit", "key change" in rs.describe_edit(pend[0]), rs.describe_edit(pend[0]))
try:
    rs.swap_clip(rn, C2)
    check("R3 swap blocked while edits pending", False)
except rs.ReviewError as e:
    check("R3 swap blocked while edits pending", "unsaved" in str(e))
mtime0 = os.path.getmtime(C1)
path, left = rs.save_clip_edits(rn)
check("R4 save_clip_edits: 0 left, file changed, manifest untouched by core", left == 0 and os.path.getmtime(C1) > mtime0 and rs.pending_edits(rn) == [])
check("R4 connections survive save", arkit_connect.connected_count(src, bs_full) == 51)
# Swap now allowed
rs.swap_clip(rn, C2)
check("R5 swap to clip 2", rs.clip_path(rn).lower().replace("/", "\\") == C2.lower())
check("R5 connections survive swap", arkit_connect.connected_count(src, bs_full) == 51 and cmds.isConnected(src + ".jawOpen", bs_full + ".jawOpen"))
check("R5 pending 0 after swap", rs.pending_edits(rn) == [])
# Discard
cmds.keyframe(curve, e=True, t=(5, 5), valueChange=0.33)
check("R6 pending 1", len(rs.pending_edits(rn)) == 1)
n = rs.discard_edits(rn)
check("R6 discard removes it, value restored, connections kept", n == 1 and rs.pending_edits(rn) == [] and
      abs(cmds.keyframe(curve, q=True, eval=True, t=(5, 5))[0] - 0.33) > 1e-6 and arkit_connect.connected_count(src, bs_full) == 51)
rs.swap_clip(rn, C1)

# 저장된 클립 1 재열기: 값 0.9 @10, 키 400 추가, 중첩 레퍼런스 무사, 아바타 편집 없음
cmds.file(C1, open=True, force=True, prompt=False)
c = "JALI_CTL_PH_AAA_ty"
check("R7 reopened clip 1 has 0.9 at f10 and the added key", abs(cmds.keyframe(c, q=True, eval=True, t=(10, 10))[0] - 0.9) < 1e-6
      and 400.0 in (cmds.keyframe(c, q=True, tc=True) or []), cmds.keyframe(c, q=True, eval=True, t=(10, 10))[0])
jrn = cmds.ls(type="reference")
check("R7 nested JALI ref intact, failedEdits 0, no avatar edit in clip",
      "JALIRN" in jrn and not (cmds.referenceQuery("JALIRN", editStrings=True, failedEdits=True, successfulEdits=False) or [])
      and not any("face_bs" in e for e in (cmds.referenceQuery("JALIRN", editStrings=True) or [])))

# ---- Open Clip 흐름: 열기 -> 임시 아바타 -> 연결 -> Save & Close 가 임시 레퍼런스를 뗀다
rs.open_clip(C2)
trn = rs.reference_temp_avatar(AVATAR)
check("R8 temp avatar referenced with fixed namespace", rs.temp_avatar_ref() == trn and cmds.referenceQuery(trn, namespace=True, shortName=True) == rs.TEMP_AVATAR_NS)
src2 = rs.arkit_out_node()
check("R8 ARKIT_OUT in an opened clip = JALI:ARKIT_OUT", src2 == "JALI:ARKIT_OUT", src2)
arkit_connect.connect(src2, rs.TEMP_AVATAR_NS + ":face_bs")
cmds.setKeyframe("JALI:CTL_PH_AAA.ty", t=300, v=0.7)
saved = rs.save_open_clip()
check("R8 save_open_clip removed the temp avatar and saved", saved.lower().replace("/", "\\") == C2.lower() and rs.temp_avatar_ref() == "")
cmds.file(C2, open=True, force=True, prompt=False)
check("R8 reopened clip 2: key 300 saved, no avatar reference inside", 300.0 in (cmds.keyframe("JALI_CTL_PH_AAA_ty", q=True, tc=True) or [])
      and not [r for r in cmds.ls(type="reference") if rs.TEMP_AVATAR_NS in r])

shutil.rmtree(work, ignore_errors=True)
finish()
